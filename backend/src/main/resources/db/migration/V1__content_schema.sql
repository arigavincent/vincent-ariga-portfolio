-- Content schema for the public portfolio.
-- Written in portable SQL so the same migrations run on PostgreSQL (production)
-- and H2 in PostgreSQL mode (local profile and fast tests).

create table site_settings (
    id              bigint       primary key check (id = 1),
    display_name    varchar(120) not null,
    brand_mark      varchar(40)  not null,
    role            varchar(160) not null,
    headline        varchar(240) not null,
    tagline         varchar(160) not null,
    bio             varchar(4000) not null,
    heritage_note   varchar(400),
    location        varchar(160) not null,
    availability    varchar(300) not null,
    email           varchar(200) not null,
    phone_display   varchar(40)  not null,
    whatsapp_number varchar(20)  not null,
    github_url      varchar(300) not null,
    footer_line     varchar(200) not null,
    seo_title       varchar(200) not null,
    seo_description varchar(400) not null,
    updated_at      timestamp with time zone not null
);

create table projects (
    id              bigint generated by default as identity primary key,
    slug            varchar(120)  not null,
    title           varchar(160)  not null,
    summary         varchar(400)  not null,
    description     varchar(8000) not null,
    category        varchar(80)   not null,
    cover_image_url varchar(500),
    repo_url        varchar(500),
    live_url        varchar(500),
    featured        boolean       not null default false,
    status          varchar(20)   not null,
    sort_order      integer       not null default 0,
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    constraint uq_projects_slug unique (slug)
);

create index idx_projects_status_sort on projects (status, sort_order);

create table project_tech_stack (
    project_id bigint      not null references projects (id) on delete cascade,
    position   integer     not null,
    name       varchar(80) not null,
    primary key (project_id, position)
);

create table project_highlights (
    project_id bigint       not null references projects (id) on delete cascade,
    position   integer      not null,
    text       varchar(300) not null,
    primary key (project_id, position)
);

create table skills (
    id         bigint generated by default as identity primary key,
    name       varchar(80) not null,
    category   varchar(20) not null,
    detail     varchar(200),
    icon_key   varchar(60),
    sort_order integer     not null default 0,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uq_skills_name unique (name)
);

create table experiences (
    id           bigint generated by default as identity primary key,
    title        varchar(160)  not null,
    organization varchar(160)  not null,
    location     varchar(160),
    start_date   date,
    end_date     date,
    current      boolean       not null default false,
    description  varchar(4000) not null,
    sort_order   integer       not null default 0,
    created_at   timestamp with time zone not null,
    updated_at   timestamp with time zone not null
);

create table education (
    id            bigint generated by default as identity primary key,
    institution   varchar(200) not null,
    qualification varchar(200) not null,
    grade         varchar(120),
    start_year    integer,
    end_year      integer,
    description   varchar(2000),
    sort_order    integer      not null default 0,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null
);

create table services (
    id          bigint generated by default as identity primary key,
    title       varchar(160)  not null,
    description varchar(2000) not null,
    icon_key    varchar(60),
    sort_order  integer       not null default 0,
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null
);

create table blog_posts (
    id              bigint generated by default as identity primary key,
    slug            varchar(160)    not null,
    title           varchar(200)    not null,
    excerpt         varchar(600)    not null,
    content         varchar(200000) not null,
    cover_image_url varchar(500),
    status          varchar(20)     not null,
    published_at    timestamp with time zone,
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    constraint uq_blog_posts_slug unique (slug)
);

create index idx_blog_posts_status_published on blog_posts (status, published_at);

create table blog_post_tags (
    blog_post_id bigint      not null references blog_posts (id) on delete cascade,
    position     integer     not null,
    name         varchar(60) not null,
    primary key (blog_post_id, position)
);
