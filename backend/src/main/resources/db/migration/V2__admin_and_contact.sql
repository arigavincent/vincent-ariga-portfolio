-- Admin accounts, refresh tokens, the contact inbox and the uploaded CV reference.

create table admin_users (
    id            bigint generated by default as identity primary key,
    username      varchar(80)  not null,
    password_hash varchar(100) not null,
    role          varchar(20)  not null,
    enabled       boolean      not null default true,
    last_login_at timestamp with time zone,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null,
    constraint uq_admin_users_username unique (username)
);

create table refresh_tokens (
    id            bigint generated by default as identity primary key,
    admin_user_id bigint      not null references admin_users (id) on delete cascade,
    token_hash    varchar(64) not null,
    expires_at    timestamp with time zone not null,
    revoked_at    timestamp with time zone,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null,
    constraint uq_refresh_tokens_hash unique (token_hash)
);

create index idx_refresh_tokens_user on refresh_tokens (admin_user_id);
create index idx_refresh_tokens_expiry on refresh_tokens (expires_at);

create table contact_messages (
    id         bigint generated by default as identity primary key,
    name       varchar(120)  not null,
    email      varchar(200)  not null,
    subject    varchar(200),
    message    varchar(5000) not null,
    status     varchar(20)   not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create index idx_contact_messages_status_created on contact_messages (status, created_at);

alter table site_settings add column cv_file_key varchar(200);
